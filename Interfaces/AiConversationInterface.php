<?php
namespace axenox\GenAI\Interfaces;

use exface\Core\Interfaces\Exceptions\ExceptionInterface;

/**
 * Authorized, exact-handler-version-bound interaction history for agents and MCP endpoints.
 * 
 * The conversation is the only component, that knows how messages are saved and loaded. It is
 * responsible for:
 * 
 * - saving and loading messages, their attachments, tool call details and opaque adapter data,
 * - restoring legacy history,
 * - identity, sequence and authorization,
 * - selecting the current model context via `getMessagesActive()`.
 * 
 * Messages always pass through the conversation: agents build every query from
 * `getMessagesActive()` and never from their own copies. The conversation keeps completed
 * messages in memory even if persisting them failed, so a storage problem does not change the
 * model context.
 * 
 * @author Andrej Kabachnik
 */
interface AiConversationInterface
{
    /**
     * Returns persisted identity.
     * 
     * @return string
     */
    public function getConversationId() : string;

    /**
     * Returns the configured owner without assuming an LLM connection.
     * 
     * @return AiTaskHandlerInterface
     */
    public function getTaskHandler() : AiTaskHandlerInterface;

    /**
     * Returns the designer-facing title.
     * 
     * @return string
     */
    public function getTitle() : string;

    /**
     * Updates the title without changing correlation or development mode.
     * 
     * @param string $title
     * @return AiConversationInterface
     */
    public function setTitle(string $title) : AiConversationInterface;

    /**
     * Returns the full history ordered by sequence, then message UID for concurrent ties.
     * 
     * @param string|null $type AiMessageTypeDataType value to include; null includes all types.
     * @return AiMessageInterface[]
     */
    public function getMessages(?string $type = null) : array;

    /**
     * Returns the messages, that are not superseded - the basis for the model context
     * 
     * Applies only API-independent rules defined by message types (e.g. future summaries replacing
     * older messages). It knows nothing about models or adapters. Agents may restrict the selection
     * further - e.g. by the context window of the model. Messages meant for designers only are
     * included too - API adapters skip them.
     * 
     * @return AiMessageInterface[]
     */
    public function getMessagesActive() : array;

    /**
     * Returns messages generated by this runtime turn, excluding concurrent turns.
     * 
     * @return AiMessageInterface[]
     */
    public function getGeneratedMessages() : array;

    /**
     * Reports whether instructions have been retained for agent orchestration.
     * 
     * @return bool
     */
    public function hasSystemPrompt() : bool;

    /**
     * Returns the retained instructions for agent orchestration.
     * 
     * @return string
     */
    public function getSystemPrompt() : string;

    /**
     * Saves the instructions once and returns conversation identity.
     * 
     * @param string $systemPrompt
     * @param array<string,mixed> $data Additional metadata for designers (JSON values only).
     * @return string
     */
    public function saveSystemPrompt(string $systemPrompt, array $data = []) : string;

    /**
     * Saves user text and attachments and returns conversation identity.
     * 
     * @param string $userPrompt
     * @param \exface\Core\Interfaces\Filesystem\FileInterface[] $files
     * @param array<string,mixed> $data Additional metadata for designers (JSON values only).
     * @return string
     */
    public function saveUserPrompt(string $userPrompt, array $files = [], array $data = []) : string;

    /**
     * Saves a tool call message before any execution and returns the saved message with its UID.
     * 
     * If the message is the response of a query, pass the query too: its usage and warnings are saved
     * along with the message.
     * 
     * @param AiToolCallMessageInterface $message Calls in request order with unique call IDs.
     * @param AiQueryInterface|null $query The query, that produced the message, if any.
     * @param array<string,mixed> $data Additional metadata for designers (JSON values only).
     * @return AiToolCallMessageInterface
     */
    public function saveToolCalls(AiToolCallMessageInterface $message, ?AiQueryInterface $query = null, array $data = []) : AiToolCallMessageInterface;

    /**
     * Adds results to an existing tool call message, never creating a second message.
     * Persists each tool error or warning as a separate diagnostic message.
     * 
     * @param string $messageId
     * @param array<string,AiToolResultInterface> $results Outcomes indexed by call ID.
     * @param array<string,mixed> $data Metadata overlay; `call_timing` (indexed by call ID) enriches the calls.
     * @return void
     */
    public function saveToolResults(string $messageId, array $results, array $data = []) : void;

    /**
     * Commits the per-call IN_PROGRESS detail immediately before invocation.
     * 
     * @param string $messageId
     * @param AiToolCallInterface $call
     * @param array<string,mixed> $data Per-call timing, argument and correlation metadata.
     * @return string
     */
    public function saveToolCallStart(string $messageId, AiToolCallInterface $call, array $data = []) : string;

    /**
     * Updates the existing detail immediately after invocation.
     * 
     * @param string $recordId
     * @param AiToolResultInterface $result
     * @param array<string,mixed> $data Per-call timing and correlation metadata.
     * @return void
     */
    public function saveToolCallEnd(string $recordId, AiToolResultInterface $result, array $data = []) : void;

    /**
     * Saves the response message of a query together with its usage and warnings.
     * 
     * @param AiQueryInterface $query
     * @return AiMessageInterface the saved message
     */
    public function saveResponse(AiQueryInterface $query) : AiMessageInterface;

    /**
     * Persists a real error; only ERROR entries have ERROR_LOG_ID.
     * 
     * @param \Throwable $error
     * @param AiToolInterface[] $tools Tools advertised when the error occurred.
     * @param array<string,mixed>|null $responseJsonSchema Optional requested answer schema.
     * @return ExceptionInterface
     */
    public function saveError(\Throwable $error, array $tools = [], ?array $responseJsonSchema = null) : ExceptionInterface;

    /**
     * Reports infrastructure errors without discarding completed results or preventing execution.
     * 
     * @param \Throwable $error
     * @return void
     */
    public function reportOperationalError(\Throwable $error) : void;

    /**
     * Persists diagnostics outside tool execution.
     * 
     * @param array<array-key,\Throwable|string> $warnings Diagnostics in their original order.
     * @return void
     */
    public function saveWarnings(array $warnings) : void;
}
